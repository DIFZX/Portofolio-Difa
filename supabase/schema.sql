create table if not exists public.portfolio_admins (
    user_id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamptz not null default now()
);

create or replace function public.is_portfolio_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.portfolio_admins
        where user_id = auth.uid()
    );
$$;

revoke all on function public.is_portfolio_admin() from public;
grant execute on function public.is_portfolio_admin() to authenticated;

create table if not exists public.portfolio_content (
    id smallint primary key default 1 check (id = 1),
    content jsonb not null default '{}'::jsonb,
    updated_by uuid references auth.users(id) on delete set null,
    updated_at timestamptz not null default now()
);

create table if not exists public.ratings (
    id bigint generated by default as identity primary key,
    name varchar(80) not null check (char_length(btrim(name)) between 1 and 80),
    origin varchar(100) check (origin is null or char_length(origin) <= 100),
    message varchar(500) not null check (char_length(btrim(message)) between 1 and 500),
    rating smallint not null check (rating between 1 and 5),
    is_visible boolean not null default true,
    created_at timestamptz not null default now()
);

create index if not exists ratings_visible_created_idx
    on public.ratings (is_visible, created_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists portfolio_content_touch_updated_at on public.portfolio_content;
create trigger portfolio_content_touch_updated_at
before update on public.portfolio_content
for each row execute function public.touch_updated_at();

alter table public.portfolio_admins enable row level security;
alter table public.portfolio_content enable row level security;
alter table public.ratings enable row level security;

drop policy if exists "Admin can view own role" on public.portfolio_admins;
create policy "Admin can view own role"
on public.portfolio_admins for select
to authenticated
using (user_id = auth.uid());

drop policy if exists "Public can read portfolio content" on public.portfolio_content;
create policy "Public can read portfolio content"
on public.portfolio_content for select
to anon, authenticated
using (true);

drop policy if exists "Admin can insert portfolio content" on public.portfolio_content;
create policy "Admin can insert portfolio content"
on public.portfolio_content for insert
to authenticated
with check (public.is_portfolio_admin() and updated_by = auth.uid());

drop policy if exists "Admin can update portfolio content" on public.portfolio_content;
create policy "Admin can update portfolio content"
on public.portfolio_content for update
to authenticated
using (public.is_portfolio_admin())
with check (public.is_portfolio_admin() and updated_by = auth.uid());

drop policy if exists "Public can read visible ratings" on public.ratings;
create policy "Public can read visible ratings"
on public.ratings for select
to anon, authenticated
using (is_visible);

drop policy if exists "Admin can read all ratings" on public.ratings;
create policy "Admin can read all ratings"
on public.ratings for select
to authenticated
using (public.is_portfolio_admin());

drop policy if exists "Public can submit ratings" on public.ratings;
create policy "Public can submit ratings"
on public.ratings for insert
to anon, authenticated
with check (
    is_visible = true
    and char_length(btrim(name)) between 1 and 80
    and char_length(btrim(message)) between 1 and 500
    and rating between 1 and 5
);

drop policy if exists "Admin can update ratings" on public.ratings;
create policy "Admin can update ratings"
on public.ratings for update
to authenticated
using (public.is_portfolio_admin())
with check (public.is_portfolio_admin());

drop policy if exists "Admin can delete ratings" on public.ratings;
create policy "Admin can delete ratings"
on public.ratings for delete
to authenticated
using (public.is_portfolio_admin());

grant select on public.portfolio_content to anon, authenticated;
grant insert, update on public.portfolio_content to authenticated;
grant select, insert on public.ratings to anon, authenticated;
grant update, delete on public.ratings to authenticated;
grant select on public.portfolio_admins to authenticated;
grant usage, select on sequence public.ratings_id_seq to anon, authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'portfolio-assets',
    'portfolio-assets',
    true,
    5242880,
    array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update set
    public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can view portfolio assets" on storage.objects;
create policy "Public can view portfolio assets"
on storage.objects for select
to public
using (bucket_id = 'portfolio-assets');

drop policy if exists "Admin can upload portfolio assets" on storage.objects;
create policy "Admin can upload portfolio assets"
on storage.objects for insert
to authenticated
with check (bucket_id = 'portfolio-assets' and public.is_portfolio_admin());

drop policy if exists "Admin can update portfolio assets" on storage.objects;
create policy "Admin can update portfolio assets"
on storage.objects for update
to authenticated
using (bucket_id = 'portfolio-assets' and public.is_portfolio_admin())
with check (bucket_id = 'portfolio-assets' and public.is_portfolio_admin());

drop policy if exists "Admin can delete portfolio assets" on storage.objects;
create policy "Admin can delete portfolio assets"
on storage.objects for delete
to authenticated
using (bucket_id = 'portfolio-assets' and public.is_portfolio_admin());

